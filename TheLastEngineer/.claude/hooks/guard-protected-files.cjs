#!/usr/bin/env node
// PreToolUse guard (matcher Edit|Write): asks before touching files Unity depends on, refuses
// Unity-generated folders. Fails open: any unexpected input lets the normal permission flow decide.
'use strict';

const path = require('path');

const DENY = [
  { re: /^(library|temp|obj)\//i, reason: 'is generated by Unity and is rebuilt on import — edit the source asset instead.' },
];

const ASK = [
  { re: /\.meta$/i, reason: 'is a .meta file: it holds the GUID every scene and prefab uses to reference this asset. Never change the guid; confirm this edit is intended.' },
  { re: /^projectsettings\//i, reason: 'is a ProjectSettings file: it changes the project for every platform and teammate. Confirm the change.' },
  { re: /^packages\/(manifest|packages-lock)\.json$/i, reason: 'changes the project packages (adds/updates dependencies for everyone). Confirm the change.' },
];

function decide(relPath) {
  for (const rule of DENY) if (rule.re.test(relPath)) return { decision: 'deny', reason: `${relPath} ${rule.reason}` };
  for (const rule of ASK) if (rule.re.test(relPath)) return { decision: 'ask', reason: `${relPath} ${rule.reason}` };
  return null;
}

function toProjectRelative(filePath, projectDir) {
  const rel = path.relative(path.resolve(projectDir), path.resolve(filePath));
  if (!rel || rel.startsWith('..') || path.isAbsolute(rel)) return null; // outside the project
  return rel.split(path.sep).join('/');
}

function main(raw) {
  let input;
  try { input = JSON.parse(raw); } catch { return; }
  const filePath = input && input.tool_input && input.tool_input.file_path;
  if (typeof filePath !== 'string' || !filePath) return;

  const projectDir = process.env.CLAUDE_PROJECT_DIR || input.cwd || process.cwd();
  const rel = toProjectRelative(filePath, projectDir);
  if (!rel) return;

  const result = decide(rel);
  if (!result) return;

  process.stdout.write(JSON.stringify({
    hookSpecificOutput: {
      hookEventName: 'PreToolUse',
      permissionDecision: result.decision,
      permissionDecisionReason: result.reason,
    },
  }));
}

if (require.main === module) {
  let raw = '';
  process.stdin.setEncoding('utf8');
  process.stdin.on('data', (chunk) => { raw += chunk; });
  // exitCode, not process.exit(): exiting early truncates piped stdout on Windows.
  process.stdin.on('end', () => { try { main(raw); } catch { /* fail open */ } process.exitCode = 0; });
}

module.exports = { decide, toProjectRelative };
